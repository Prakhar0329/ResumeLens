"use client";

import { useEffect, useState } from "react";

import { getHealth } from "@/lib/api";
import { formatPercent } from "@/lib/format";
import type { ScoringConfig } from "@/types/api";

/** Backend defaults (backend/app/config.py), shown when the API can't be reached. */
const DEFAULT_CONFIG: ScoringConfig = {
  weights: { skill_coverage: 0.5, semantic_similarity: 0.35, keyword_overlap: 0.15 },
  semantic_band: { floor: 0.2, ceiling: 0.75 },
  keyword_band: { floor: 0.02, ceiling: 0.4 },
  skill_priority_weights: { required: 2, unspecified: 1, preferred: 0.5 },
  verdict_thresholds: { partial: 40, strong: 65, excellent: 85 },
  limits: { max_upload_mb: 5, max_pdf_pages: 10, min_jd_chars: 100, max_jd_chars: 15000 },
};

const PIPELINE = [
  {
    title: "Read the PDF",
    body: "Text is extracted with pdfplumber, falling back to PyMuPDF. PDFs without a text layer (scans) are rejected because OCR isn't supported.",
  },
  {
    title: "Clean the text",
    body: "Unicode is normalised, hyphenated line breaks are joined and bullet symbols are unified. Emails, phone numbers and links are removed before any analysis.",
  },
  {
    title: "Find sections and chunks",
    body: "Headings such as Experience, Projects and Skills split the resume into sections, and each section into bullet-sized chunks. The job description is split into requirement sentences, each tagged required, preferred or neither from cues like “must have” and “nice to have”.",
  },
  {
    title: "Match skills",
    body: "A curated list of over 400 skills and their aliases (postgres → PostgreSQL, k8s → Kubernetes) is matched with spaCy's PhraseMatcher, including tricky names such as C++, C#, .NET and Node.js.",
  },
  {
    title: "Compare meaning",
    body: "Every requirement and resume chunk is turned into a sentence embedding with all-MiniLM-L6-v2. For each requirement, the closest chunk by cosine similarity is its best match.",
  },
  {
    title: "Compare wording",
    body: "A TF-IDF model measures exact shared terms between the whole resume and the whole posting, the way a keyword-based screener would.",
  },
  {
    title: "Score and suggest",
    body: "The three signals are combined into one score, and a set of fixed rules turns the gaps into suggestions.",
  },
];

function Formula({ children }: { children: string }) {
  return (
    <pre className="overflow-x-auto rounded-md border border-rule bg-surface px-4 py-3 text-sm leading-relaxed text-ink">
      <code>{children}</code>
    </pre>
  );
}

export default function AboutPage() {
  const [config, setConfig] = useState<ScoringConfig>(DEFAULT_CONFIG);
  const [live, setLive] = useState(false);

  useEffect(() => {
    const controller = new AbortController();
    getHealth(controller.signal)
      .then((health) => {
        setConfig(health.config);
        setLive(true);
      })
      .catch(() => setLive(false));
    return () => controller.abort();
  }, []);

  const w = config.weights;
  const p = config.skill_priority_weights;
  const v = config.verdict_thresholds;

  return (
    <div className="max-w-prose space-y-12">
      <header>
        <h1 className="text-3xl font-semibold">How ResumeLens works</h1>
        <p className="mt-3 text-lg text-graphite">
          Every score comes from three measurable signals and a fixed formula. Nothing is generated by a
          language model except the optional bullet rewrite.
        </p>
      </header>

      <section aria-labelledby="pipeline">
        <h2 id="pipeline" className="section-title">
          The pipeline
        </h2>
        <ol className="mt-4 space-y-5">
          {PIPELINE.map((step, index) => (
            <li key={step.title} className="grid grid-cols-[2rem_1fr] gap-2">
              <span aria-hidden className="pt-px font-semibold tabular-nums text-lens">
                {index + 1}
              </span>
              <div>
                <h3 className="font-semibold">{step.title}</h3>
                <p className="mt-1 text-graphite">{step.body}</p>
              </div>
            </li>
          ))}
        </ol>
      </section>

      <section aria-labelledby="scoring" className="space-y-4">
        <h2 id="scoring" className="section-title">
          The score
        </h2>
        <p className="text-sm text-graphite">
          {live
            ? "Values below are read live from the running server."
            : "Showing default values; the server could not be reached."}
        </p>
        <Formula>
          {`overall = ${w.skill_coverage.toFixed(2)} × skill coverage\n        + ${w.semantic_similarity.toFixed(
            2,
          )} × semantic similarity\n        + ${w.keyword_overlap.toFixed(2)} × keyword overlap`}
        </Formula>
        <h3 className="pt-2 font-semibold">Skill coverage ({formatPercent(w.skill_coverage)})</h3>
        <p className="text-graphite">
          The weighted share of the posting&apos;s skills that appear on your resume. Required skills count{" "}
          {p.required}, skills mentioned without a label count {p.unspecified}, and nice-to-haves count{" "}
          {p.preferred}. If the posting names no known skills, this signal is dropped and its weight is shared
          between the other two.
        </p>
        <h3 className="pt-2 font-semibold">Semantic similarity ({formatPercent(w.semantic_similarity)})</h3>
        <p className="text-graphite">
          For each requirement, the cosine similarity of its closest resume chunk; these are averaged. Raw
          cosine values cluster in a narrow range, so the average is rescaled linearly from [
          {config.semantic_band.floor}, {config.semantic_band.ceiling}] to 0–100 and clipped. This catches
          paraphrases such as &ldquo;built HTTP services&rdquo; for &ldquo;REST API development&rdquo;.
        </p>
        <h3 className="pt-2 font-semibold">Keyword overlap ({formatPercent(w.keyword_overlap)})</h3>
        <p className="text-graphite">
          TF-IDF cosine similarity of the full documents (single words and two-word phrases), rescaled from [
          {config.keyword_band.floor}, {config.keyword_band.ceiling}] to 0–100. Applicant tracking systems
          often match words literally, so exact terms still matter.
        </p>
        <h3 className="pt-2 font-semibold">Verdicts</h3>
        <ul className="space-y-1 text-graphite">
          <li>Below {v.partial}: weak match</li>
          <li>
            {v.partial} to {(v.strong - 0.1).toFixed(1)}: partial match
          </li>
          <li>
            {v.strong} to {(v.excellent - 0.1).toFixed(1)}: strong match
          </li>
          <li>{v.excellent} and above: excellent match</li>
        </ul>
      </section>

      <section aria-labelledby="limits" className="space-y-3">
        <h2 id="limits" className="section-title">
          What the score can&apos;t tell you
        </h2>
        <ul className="list-disc space-y-2 pl-5 text-graphite">
          <li>
            English only. Scanned PDFs aren&apos;t read, and two-column layouts can come out in the wrong
            order.
          </li>
          <li>
            Skills outside the built-in list aren&apos;t detected, and &ldquo;A or B&rdquo; in a posting
            counts both as needed.
          </li>
          <li>Required/preferred tags come from phrasing, so unusual postings can be tagged wrongly.</li>
          <li>
            The weights and bands are starting values. They should be calibrated against human judgments with
            the project&apos;s evaluation script before the numbers are treated as meaningful.
          </li>
          <li>A high score means the wording lines up, not that you will get the job.</li>
        </ul>
      </section>

      <section aria-labelledby="privacy" className="space-y-3">
        <h2 id="privacy" className="section-title">
          Privacy
        </h2>
        <ul className="list-disc space-y-2 pl-5 text-graphite">
          <li>
            Your resume text is never written to the database or to logs; it exists only while the request
            runs.
          </li>
          <li>
            With &ldquo;Save to history&rdquo; on, the server keeps scores, skill lists, suggestions, job
            requirement sentences and a SHA-256 fingerprint of the file. Resume excerpts are removed before
            saving.
          </li>
          <li>
            With it off, nothing is stored on the server. Full results stay in this browser tab until you
            close it.
          </li>
          <li>You can delete one analysis or your entire history at any time from the History page.</li>
          <li>
            The optional bullet rewrite sends only the bullet you paste, your chosen skills and a few job
            requirements to Anthropic&apos;s API, and only if the server has it enabled.
          </li>
          <li>
            Uploads are limited to PDFs of {config.limits.max_upload_mb} MB and {config.limits.max_pdf_pages}{" "}
            pages.
          </li>
        </ul>
      </section>
    </div>
  );
}
